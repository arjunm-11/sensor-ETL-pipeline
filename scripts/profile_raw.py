"""
Exploratory profile of the raw Intel Berkeley Lab file (data.txt.gz).

Purpose: look at the data *before* writing any quality rules, so every
rule in later phases is justified by something we actually observed.

Usage:
    python scripts/profile_raw.py data/raw docs/data_profile.md

All numbers in the generated report are computed here; nothing is typed by hand.
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

COLS = ["date", "time", "epoch", "moteid", "temperature", "humidity", "light", "voltage"]
NUMERIC = ["epoch", "moteid", "temperature", "humidity", "light", "voltage"]
SAMPLE_PERIOD_S = 31  # documented sampling interval of each mote


def load_raw(path: Path) -> pd.DataFrame:
    # sep=" " (a single space, not regex \s+) is deliberate: in this file an
    # empty field is written as two consecutive spaces. Splitting on runs of
    # whitespace would shift later values left (e.g. voltage into "light").
    # dtype=str + keep_default_na=False keeps every token exactly as written.
    return pd.read_csv(
        path, sep=" ", header=None, names=COLS, dtype=str,
        keep_default_na=False, compression="gzip",
    )


def pct(n, d):
    return f"{100 * n / d:.2f}%" if d else "n/a"


def md_table(df: pd.DataFrame) -> str:
    """Minimal markdown table renderer (avoids adding the `tabulate` dependency)."""
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join(str(v) for v in row) + " |")
    return "\n".join(lines)


def main(raw_dir: Path, out_path: Path) -> None:
    raw = load_raw(raw_dir / "data.txt.gz")
    n = len(raw)
    out = ["# Raw data profile: Intel Berkeley Lab `data.txt.gz`", "",
           f"Generated by `scripts/profile_raw.py`. Total lines: **{n:,}**.", ""]

    # ---- 1. Completeness: how many positions are empty, per column ----------
    out += ["## 1. Field completeness", "",
            "Every line has exactly 8 single-space-separated positions; missing values are empty strings.", ""]
    empties = pd.DataFrame({
        "column": COLS,
        "empty": [(raw[c] == "").sum() for c in COLS],
    })
    empties["empty_pct"] = [pct(e, n) for e in empties["empty"]]
    out += [md_table(empties), ""]
    pattern = raw[NUMERIC].ne("").apply(lambda r: "".join("x" if v else "." for v in r), axis=1)
    pat_counts = pattern.value_counts().rename_axis("present (epoch,mote,temp,hum,light,volt)").reset_index(name="rows")
    out += ["Present/missing pattern per row (`x` = present, `.` = empty):", "", md_table(pat_counts), ""]

    # ---- 2. Type parse: does every non-empty token parse as a number/date? ---
    num = raw[NUMERIC].apply(pd.to_numeric, errors="coerce")
    bad_parse = {c: int(((raw[c] != "") & num[c].isna()).sum()) for c in NUMERIC}
    ts = pd.to_datetime(raw["date"] + " " + raw["time"], errors="coerce", format="%Y-%m-%d %H:%M:%S.%f")
    # Some times may lack fractional seconds; retry those with a second format.
    retry = ts.isna()
    ts[retry] = pd.to_datetime(raw.loc[retry, "date"] + " " + raw.loc[retry, "time"],
                               errors="coerce", format="%Y-%m-%d %H:%M:%S")
    out += ["## 2. Type parsing", "",
            f"- Non-empty tokens that fail numeric parsing: {bad_parse}",
            f"- Timestamps failing to parse: {int(ts.isna().sum()):,}",
            f"- Timestamps without fractional seconds: {int(retry.sum() - ts[retry].isna().sum()):,}",
            f"- Timestamp range: {ts.min()} → {ts.max()}",
            f"- Lines out of chronological order vs. previous line: {int((ts.diff().dt.total_seconds() < 0).sum()):,}",
            ""]
    non_int_epoch = int((num["epoch"].notna() & (num["epoch"] % 1 != 0)).sum())
    out += [f"- Non-integer epochs: {non_int_epoch}", f"- Epoch range: {num['epoch'].min():.0f} → {num['epoch'].max():.0f}", ""]

    df = num.copy()
    df["ts"] = ts

    # ---- 3. Mote IDs ----------------------------------------------------------
    locs = pd.read_csv(raw_dir / "mote_locs.txt", sep=" ", header=None, names=["moteid", "x", "y"])
    known = set(locs["moteid"])
    mote_counts = df["moteid"].value_counts(dropna=False)
    unknown = mote_counts[~mote_counts.index.isin(known)]
    out += ["## 3. Mote IDs", "",
            f"- `mote_locs.txt` lists {len(known)} motes (ids {min(known)}–{max(known)}).",
            f"- Distinct mote ids in data (incl. empty): {len(mote_counts)}",
            "- Ids not in `mote_locs.txt` (id → rows):", ""]
    out += [md_table(unknown.rename_axis("moteid").reset_index(name="rows")), ""]
    silent = sorted(known - set(df["moteid"].dropna()))
    out += [f"- Known motes with zero readings: {silent or 'none'}", ""]
    per_mote = df[df["moteid"].isin(known)].groupby("moteid").agg(
        rows=("ts", "size"), first=("ts", "min"), last=("ts", "max"))
    out += ["Rows per known mote (min / median / max): "
            f"{per_mote['rows'].min():,} / {int(per_mote['rows'].median()):,} / {per_mote['rows'].max():,}", ""]

    # ---- 4. Value distributions ----------------------------------------------
    qs = [0, 0.001, 0.01, 0.25, 0.5, 0.75, 0.99, 0.999, 1]
    dist = df[["temperature", "humidity", "light", "voltage"]].quantile(qs).T
    dist.columns = [f"p{q*100:g}" for q in qs]
    out += ["## 4. Value distributions (all rows, non-empty values)", "",
            md_table(dist.round(3).reset_index(names="column")), ""]

    # Values that repeat suspiciously often hint at sensor faults / sentinels.
    out += ["Most frequent exact values (sentinel / stuck-value hunting):", ""]
    for c in ["temperature", "humidity"]:
        top = raw.loc[raw[c] != "", c].value_counts().head(5)
        out += [f"- {c}: " + ", ".join(f"`{v}` × {k:,}" for v, k in top.items())]
    out += [""]

    # Physical plausibility. Thresholds here are *exploratory*; final rules are
    # decided in Phase 3 based on what this section shows.
    t, h, v, l = df["temperature"], df["humidity"], df["voltage"], df["light"]
    checks = {
        "temperature < 0 °C (indoor lab)": (t < 0).sum(),
        "temperature > 50 °C": (t > 50).sum(),
        "temperature > 100 °C": (t > 100).sum(),
        "humidity < 0 %": (h < 0).sum(),
        "humidity > 100 %": (h > 100).sum(),
        "light < 0": (l < 0).sum(),
        "voltage < 2.0 V": (v < 2.0).sum(),
        "voltage > 3.0 V": (v > 3.0).sum(),
    }
    out += ["Rows outside plausible ranges:", "",
            md_table(pd.DataFrame({"condition": list(checks), "rows": [f"{int(x):,}" for x in checks.values()],
                                   "pct": [pct(int(x), n) for x in checks.values()]})), ""]

    # Relationship between battery voltage and implausible temperature: if the
    # bad readings cluster at low voltage, battery death is the root cause.
    bins = [0, 2.0, 2.2, 2.3, 2.4, 2.5, 2.6, 2.7, 10]
    vb = pd.cut(v, bins=bins)
    rel = pd.DataFrame({"rows": vb.value_counts().sort_index(),
                        "temp>50": (t > 50).groupby(vb, observed=False).sum(),
                        "hum<0": (h < 0).groupby(vb, observed=False).sum()})
    rel["temp>50 rate"] = (rel["temp>50"] / rel["rows"]).map(lambda x: f"{x:.2%}" if pd.notna(x) else "")
    out += ["Implausible readings by voltage band:", "",
            md_table(rel.reset_index(names="voltage band")), ""]

    # ---- 5. Duplicates --------------------------------------------------------
    exact_dup = raw.duplicated().sum()
    key = df[["moteid", "epoch"]]
    key_dup_mask = key.notna().all(axis=1) & key.duplicated(keep=False)
    key_dups = df[key_dup_mask]
    # Among (mote, epoch) duplicates, do the sensor values agree?
    conflicting = (key_dups.groupby(["moteid", "epoch"])[["temperature", "humidity", "light", "voltage"]]
                   .nunique(dropna=False).gt(1).any(axis=1).sum())
    out += ["## 5. Duplicates", "",
            f"- Exact duplicate lines (all 8 tokens equal): {int(exact_dup):,}",
            f"- Rows sharing a (moteid, epoch) with another row: {len(key_dups):,} "
            f"in {key_dups.groupby(['moteid','epoch']).ngroups:,} groups",
            f"- Of those groups, ones where sensor values differ: {int(conflicting):,}",
            f"- Max rows in one (moteid, epoch) group: {int(key.value_counts().max())}",
            ""]
    # How far apart in time are rows that share (moteid, epoch)? Seconds apart
    # = the same packet received twice. Days apart = the epoch counter restarted,
    # so the "duplicate" is actually a different reading.
    span = key_dups.groupby(["moteid", "epoch"])["ts"].agg(lambda s: (s.max() - s.min()).total_seconds())
    out += [f"- Time span inside those groups: median {span.median()/86400:.2f} days; "
            f"groups spanning < 60 s: {int((span < 60).sum())}; > 1 day: {int((span > 86400).sum()):,}",
            ""]

    # ---- 6. Epoch vs timestamp consistency -----------------------------------
    # Epoch is a network-wide sample counter (one tick per 31 s). So
    # ts - epoch*31s should be roughly constant; large residuals mean the
    # timestamp (assigned on arrival at the base station) and the epoch disagree.
    good = df.dropna(subset=["epoch", "ts"])
    offset = good["ts"] - pd.to_timedelta(good["epoch"] * SAMPLE_PERIOD_S, unit="s")
    base = offset.median()
    resid_h = (offset - base).dt.total_seconds() / 3600
    out += ["## 6. Epoch vs timestamp", "",
            f"Assuming `ts ≈ T0 + epoch × {SAMPLE_PERIOD_S}s`, median T0 = {base}.", "",
            "Distribution of |residual| (hours):", ""]
    a = resid_h.abs()
    for lo, hi in [(0, 1), (1, 6), (6, 24), (24, 24 * 7), (24 * 7, 1e9)]:
        out += [f"- {lo}–{hi if hi < 1e9 else '∞'} h: {int(((a >= lo) & (a < hi)).sum()):,}"]
    # Epoch going backwards within a single mote's time-ordered stream suggests a counter reset.
    srt = good.sort_values(["moteid", "ts"])
    back = (srt.groupby("moteid")["epoch"].diff() < 0).sum()
    out += ["", f"- Within a mote (ordered by ts), epoch decreases: {int(back):,} times", ""]
    # Compare epoch-derived elapsed time with wall-clock elapsed time per mote.
    span = srt[srt["moteid"].isin(known)].groupby("moteid").agg(
        e0=("epoch", "min"), e1=("epoch", "max"), t0=("ts", "min"), t1=("ts", "max"))
    span["s_per_epoch"] = (span["t1"] - span["t0"]).dt.total_seconds() / (span["e1"] - span["e0"])
    out += [f"- Wall-clock seconds per epoch tick, per mote (min/median/max): "
            f"{span['s_per_epoch'].min():.1f} / {span['s_per_epoch'].median():.1f} / {span['s_per_epoch'].max():.1f}", ""]

    # ---- 7. Gaps / silent motes ----------------------------------------------
    gaps = srt[srt["moteid"].isin(known)].copy()
    gaps["gap_s"] = gaps.groupby("moteid")["ts"].diff().dt.total_seconds()
    g = gaps["gap_s"].dropna()
    out += ["## 7. Reading gaps and silent motes", "",
            f"Gap between consecutive readings of the same mote (expected ≈ {SAMPLE_PERIOD_S}s):", "",
            f"- median {g.median():.1f}s, p90 {g.quantile(.9):.1f}s, p99 {g.quantile(.99):.1f}s, max {g.max()/86400:.1f} days",
            f"- gaps > 10 min: {int((g > 600).sum()):,}; > 1 h: {int((g > 3600).sum()):,}; > 1 day: {int((g > 86400).sum()):,}",
            ""]
    data_end = df["ts"].max()
    per_mote["days_silent_before_end"] = ((data_end - per_mote["last"]).dt.total_seconds() / 86400).round(1)
    expected = ((per_mote["last"] - per_mote["first"]).dt.total_seconds() / SAMPLE_PERIOD_S)
    per_mote["delivery_rate"] = (per_mote["rows"] / expected).map(lambda x: f"{x:.1%}")
    early = per_mote.sort_values("last").head(10).reset_index()
    early["first"] = early["first"].dt.strftime("%Y-%m-%d %H:%M")
    early["last"] = early["last"].dt.strftime("%Y-%m-%d %H:%M")
    out += [f"Motes that stopped earliest (data ends {data_end}):", "", md_table(early), "",
            "Delivery rate = rows received ÷ (active span / 31s). Median across motes: "
            f"{(per_mote['rows'] / expected).median():.1%}", ""]

    # Final voltage readings: do motes die with low batteries?
    last_v = srt[srt["moteid"].isin(known)].dropna(subset=["voltage"]).groupby("moteid")["voltage"].last()
    out += [f"Last reported voltage per mote (min / median / max): "
            f"{last_v.min():.3f} / {last_v.median():.3f} / {last_v.max():.3f} V", ""]

    # ---- 8. Reference files ---------------------------------------------------
    conn_lines = (raw_dir / "connectivity.txt").read_text().splitlines()
    conn_nf = pd.Series([len(l.split()) for l in conn_lines]).value_counts()
    out += ["## 8. Reference files", "",
            f"- `mote_locs.txt`: {len(locs)} rows, columns (moteid, x, y), ids {locs.moteid.min()}–{locs.moteid.max()}, unique={locs.moteid.is_unique}",
            f"- `connectivity.txt`: {len(conn_lines)} lines; whitespace-field counts {dict(conn_nf)}", ""]

    out_path.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {out_path}")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
